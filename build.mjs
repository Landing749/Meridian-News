// Builds the static site into dist/ (what GitHub Pages serves).
//   BASE_PATH   path prefix when served from a project site, e.g. "/my-repo" (empty for a custom domain or user site)
//   SITE_URL    public address, used when prerendering
import esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const at = (...p) => path.join(root, ...p);
const BASE = (process.env.BASE_PATH || '').replace(/\/+$/, '');
const V = Date.now().toString(36);
const rmrf = p => fs.rmSync(p, { recursive: true, force: true });
const copy = (from, to) => fs.cpSync(from, to, { recursive: true });

rmrf(at('dist')); fs.mkdirSync(at('dist/assets'), { recursive: true });

// 1. The page scripts (admin.js, editor.js, ...) become functions inside the bundle: no eval, and the strict CSP stays valid.
let gen = '// generated by build.mjs\nmodule.exports = {\n';
for (const f of fs.readdirSync(at('public/js')).filter(f => f.endsWith('.js'))) gen += `${JSON.stringify(f.replace(/\.js$/, ''))}: function () {\n${fs.readFileSync(at('public/js', f), 'utf8')}\n},\n`;
fs.writeFileSync(at('src/browser/page-scripts.generated.js'), gen + '};\n');

// 2. Bundle the app.
await esbuild.build({
  entryPoints: [at('src/browser/entry.js')], outfile: at('dist/assets/app.js'), bundle: true, minify: true, format: 'iife', platform: 'browser', target: ['es2020'],
  alias: { express: at('src/browser/express.js'), multer: at('src/browser/multer.js'), path: at('src/browser/path.js') },
  inject: [at('src/browser/buffer-shim.js')], legalComments: 'none', logLevel: 'info',
  define: { 'process.env.NODE_ENV': '"production"', 'process.env.SITE_URL': JSON.stringify(process.env.SITE_URL || ''), global: 'globalThis' },
});

// 3. Static files. CSS fonts are written as /fonts/...; on a project site they need the repository prefix.
copy(at('public'), at('dist'));
fs.rmSync(at('dist/js'), { recursive: true, force: true }); // page scripts live inside app.js
if (BASE) for (const f of fs.readdirSync(at('dist/css'))) { const p = at('dist/css', f); fs.writeFileSync(p, fs.readFileSync(p, 'utf8').replace(/url\(\s*(['"]?)\/(?!\/)/g, `url($1${BASE}/`)); }
fs.writeFileSync(at('dist/assets/boot.js'),
  `window.MMG_BASE=${JSON.stringify(BASE)};\n// Clickjacking guard (GitHub Pages cannot send X-Frame-Options): only this site may frame itself.\ntry{if(top!==self&&top.location.origin!==location.origin)top.location=self.location}catch(e){try{top.location=self.location}catch(e2){}}\n`);
fs.copyFileSync(at('config.js'), at('dist/config.js'));
const html = fs.readFileSync(at('index.template.html'), 'utf8').replaceAll('%BASE%', BASE).replaceAll('%V%', V);
fs.writeFileSync(at('dist/index.html'), html);
fs.writeFileSync(at('dist/404.html'), html); // GitHub Pages serves this for any address that is not a file; the app reads the address and shows the right page
fs.writeFileSync(at('dist/.nojekyll'), '');
if (fs.existsSync(at('CNAME'))) fs.copyFileSync(at('CNAME'), at('dist/CNAME'));
console.log(`built dist/ (base path "${BASE || '/'}", version ${V})`);
